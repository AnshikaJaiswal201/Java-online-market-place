-- ONLINE MARKETPLACE - ORACLE 21c XE DDL SCHEMA SCRIPT (3NF NORMALIZED)
-- Database: Oracle Database 21c XE
-- Compatibility: Oracle 19c / 21c XE
-- ============================================================================

-- Clean up existing tables (execute with CASCADE CONSTRAINTS)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'ORDER_ITEMS', 'ORDERS', 'CART_ITEMS', 'INVENTORY', 
        'PRODUCTS', 'CATEGORIES', 'USER_ROLES', 'ROLES', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ============================================================================
-- 1. USERS & RBAC TABLES
-- ============================================================================

CREATE TABLE roles (
    role_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    role_name       VARCHAR2(30) NOT NULL,
    description     VARCHAR2(150),
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_role_name UNIQUE (role_name)
);

CREATE TABLE users (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1),
    email           VARCHAR2(100) NOT NULL,
    password_hash   VARCHAR2(255) NOT NULL,
    full_name       VARCHAR2(100) NOT NULL,
    phone_number    VARCHAR2(15),
    address_line1   VARCHAR2(200),
    city            VARCHAR2(50),
    state           VARCHAR2(50),
    pin_code        VARCHAR2(10),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_active CHECK (is_active IN (0, 1))
);

CREATE TABLE user_roles (
    user_id         NUMBER NOT NULL,
    role_id         NUMBER NOT NULL,
    assigned_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES roles (role_id) ON DELETE CASCADE
);

-- ============================================================================
-- 2. CATEGORIES & PRODUCTS (Soft-Delete Enabled)
-- ============================================================================

CREATE TABLE categories (
    category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 1),
    category_name   VARCHAR2(80) NOT NULL,
    description     VARCHAR2(255),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name UNIQUE (category_name),
    CONSTRAINT chk_categories_active CHECK (is_active IN (0, 1))
);

CREATE TABLE products (
    product_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 5000 INCREMENT BY 1),
    seller_id       NUMBER NOT NULL,
    category_id     NUMBER NOT NULL,
    name            VARCHAR2(150) NOT NULL,
    description     CLOB,
    price           NUMBER(12, 2) NOT NULL,
    sku             VARCHAR2(60) NOT NULL,
    image_url       VARCHAR2(500),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_active CHECK (is_active IN (0, 1))
);

-- ============================================================================
-- 3. INVENTORY MANAGEMENT (Real-Time Stock Per SKU)
-- ============================================================================

CREATE TABLE inventory (
    inventory_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 5000 INCREMENT BY 1),
    product_id          NUMBER NOT NULL,
    stock_quantity      NUMBER(10) DEFAULT 0 NOT NULL,
    low_stock_threshold NUMBER(10) DEFAULT 5 NOT NULL,
    last_restocked_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_inventory PRIMARY KEY (inventory_id),
    CONSTRAINT uq_inventory_product UNIQUE (product_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (product_id) ON DELETE CASCADE,
    CONSTRAINT chk_inventory_stock CHECK (stock_quantity >= 0),
    CONSTRAINT chk_inventory_threshold CHECK (low_stock_threshold >= 0)
);

-- ============================================================================
-- 4. SHOPPING CART
-- ============================================================================

CREATE TABLE cart_items (
    cart_item_id    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    user_id         NUMBER NOT NULL,
    product_id      NUMBER NOT NULL,
    quantity        NUMBER(5) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_cart_items PRIMARY KEY (cart_item_id),
    CONSTRAINT uq_user_product_cart UNIQUE (user_id, product_id),
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_product FOREIGN KEY (product_id) REFERENCES products (product_id) ON DELETE CASCADE,
    CONSTRAINT chk_cart_quantity CHECK (quantity > 0)
);

-- ============================================================================
-- 5. ORDERS & ORDER ITEMS
-- ============================================================================

CREATE TABLE orders (
    order_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 10000 INCREMENT BY 1),
    order_number        VARCHAR2(40) NOT NULL,
    customer_id         NUMBER NOT NULL,
    total_amount        NUMBER(12, 2) NOT NULL,
    order_status        VARCHAR2(20) DEFAULT 'PLACED' NOT NULL,
    shipping_address    VARCHAR2(500) NOT NULL,
    payment_method      VARCHAR2(30) DEFAULT 'UPI' NOT NULL,
    payment_status      VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES users (user_id),
    CONSTRAINT chk_order_status CHECK (order_status IN ('PLACED', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT chk_payment_status CHECK (payment_status IN ('PENDING', 'PAID', 'FAILED')),
    CONSTRAINT chk_orders_total CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
    order_item_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000 INCREMENT BY 1),
    order_id        NUMBER NOT NULL,
    product_id      NUMBER NOT NULL,
    seller_id       NUMBER NOT NULL,
    quantity        NUMBER(5) NOT NULL,
    unit_price      NUMBER(12, 2) NOT NULL,
    subtotal        NUMBER(12, 2) NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT fk_oi_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT fk_oi_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT chk_oi_quantity CHECK (quantity > 0),
    CONSTRAINT chk_oi_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_oi_subtotal CHECK (subtotal >= 0)
);

-- ============================================================================
-- 6. PERFORMANCE INDEXES
-- ============================================================================

CREATE INDEX idx_products_seller ON products (seller_id);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_active ON products (is_active);
CREATE INDEX idx_inventory_product ON inventory (product_id);
CREATE INDEX idx_cart_user ON cart_items (user_id);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (order_status);
CREATE INDEX idx_oi_order ON order_items (order_id);
CREATE INDEX idx_oi_seller ON order_items (seller_id);
CREATE INDEX idx_oi_product ON order_items (product_id);

COMMIT;
